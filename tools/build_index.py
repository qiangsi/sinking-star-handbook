# -*- coding: utf-8 -*-
"""Build the compact level index for the Sinking Star Handbook site.

Reads the public-domain (Unlicense) dataset from joric/ootss and emits:
  - levels-index.json : one entry per Level_Entry marker
  - stats.json        : aggregate counts for the coverage chapter

Usage: python -I build_index.py <data_dir> <out_dir>
"""
import json
import sys
from collections import Counter
from pathlib import Path

SOURCE_REPO = "https://github.com/joric/ootss"
SOURCE_MAP = "https://joric.github.io/ootss/"


def point_in_poly(x, y, poly):
    """Ray-casting point-in-polygon test."""
    inside = False
    j = len(poly) - 1
    for i in range(len(poly)):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside


def load(data_dir, name):
    with open(Path(data_dir) / name, encoding="utf-8") as fh:
        return json.load(fh)


def main(data_dir, out_dir):
    data_dir = Path(data_dir)
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    markers = load(data_dir, "markers.json")
    regions = load(data_dir, "regions.json")
    sol_auto = {e["name"]: e["solution"] for e in load(data_dir, "solutions.json")}
    sol_comm = {}
    for line in open(data_dir / "solutions.txt", encoding="utf-8"):
        line = line.strip()
        if not line:
            continue
        name, _, mv = line.partition(":")
        sol_comm[name.strip()] = mv.strip()
    wt_names = {}
    for line in open(data_dir / "wt.txt", encoding="utf-8"):
        parts = [p.strip() for p in line.strip().split(",")]
        if len(parts) >= 3 and parts[0]:
            wt_names[parts[0]] = parts[2]

    polys = [
        (f["properties"]["name"], f["properties"]["title"], f["geometry"]["coordinates"][0])
        for f in regions["features"]
    ]

    entries = []
    for f in markers["features"]:
        p = f["properties"]
        if p.get("type") != "Level_Entry":
            continue
        x, y, z = f["geometry"]["coordinates"]
        region = ""
        for rname, rtitle, poly in polys:
            if point_in_poly(x, y, poly):
                region = rtitle
                break
        name = p["level_name"]
        q, mv = 0, ""
        if name in sol_comm:
            q, mv = 1, sol_comm[name]
        elif name in sol_auto:
            q, mv = 2, sol_auto[name]
        entries.append(
            {
                "n": name,                      # internal level name (community slug)
                "w": wt_names.get(name, ""),    # community display name from wt.txt
                "s": p.get("level_set", ""),    # mechanic set
                "r": region,                    # big region from regions.json polygon
                "c": [x, y, z],                 # map coordinates, z = height
                "q": q,                         # 0 none / 1 community route / 2 auto-solved
                "m": mv,                        # compact move string
            }
        )

    entries.sort(key=lambda e: (e["s"], e["n"]))
    with open(out_dir / "levels-index.json", "w", encoding="utf-8") as fh:
        json.dump(entries, fh, ensure_ascii=False, separators=(",", ":"))

    # script-tag wrapper so the index also loads when opened from file://
    payload = json.dumps(entries, ensure_ascii=False, separators=(",", ":"))
    with open(out_dir / "levels-index.js", "w", encoding="utf-8") as fh:
        fh.write("// generated by tools/build_index.py from joric/ootss (Unlicense)\n")
        fh.write("window.HANDBOOK_LEVELS=")
        fh.write(payload)
        fh.write(";\n")

    set_counts = Counter(e["s"] for e in entries)
    region_counts = Counter(e["r"] or "(未划入七大区域)" for e in entries)
    q_counts = Counter(e["q"] for e in entries)

    # sanity probe: which sets use the F/B (front/back) move letters
    fb_sets = Counter(
        e["s"] for e in entries if "F" in e["m"] or "B" in e["m"]
    )

    stats = {
        "generated": "2026-11-08",
        "source_repo": SOURCE_REPO,
        "source_map": SOURCE_MAP,
        "source_license": "Unlicense (public domain)",
        "total_levels": len(entries),
        "with_community_route": q_counts.get(1, 0),
        "with_auto_solution": q_counts.get(2, 0),
        "no_solution": q_counts.get(0, 0),
        "set_counts": dict(set_counts.most_common()),
        "region_counts": dict(region_counts.most_common()),
        "fb_move_sets": dict(fb_sets.most_common()),
    }
    with open(out_dir / "stats.json", "w", encoding="utf-8") as fh:
        json.dump(stats, fh, ensure_ascii=False, indent=2)

    print("levels:", stats["total_levels"])
    print("community routes:", stats["with_community_route"])
    print("auto solutions:", stats["with_auto_solution"])
    print("none:", stats["no_solution"])
    print("sets:", len(set_counts))
    print("regions:", dict(region_counts))
    print("F/B letters appear in sets:", dict(fb_sets))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: python -I build_index.py <data_dir> <out_dir>")
    main(sys.argv[1], sys.argv[2])
